    public com.campingparty.modelo.Reserva getReservaSeleccionada() {
        int fila = jTable1.getSelectedRow();
        if (fila >= 0 && reservas != null && fila < reservas.size()) {
            return reservas.get(fila);
        }
        return null;
    }

