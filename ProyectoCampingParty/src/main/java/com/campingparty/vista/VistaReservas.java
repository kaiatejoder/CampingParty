    private void actualizarTabla() {
        if (reservas == null || reservas.isEmpty()) return;
        Object[][] datos = new Object[reservas.size()][2];
        for (int i = 0; i < reservas.size(); i++) {
            datos[i][0] = i + 1;
            datos[i][1] = cliente != null ? cliente.getNombre() : "";
        }
        jTable1.setModel(new javax.swing.table.DefaultTableModel(datos, new String[]{"IDReserva", "Cliente"}));
    }
    
